-- FP&A Web App — initial schema. Mirrors docs/3-plan/erd.md exactly (16 tables).
--
-- Type mapping from the ERD:  int -> integer · string -> text · decimal -> numeric ·
--   date -> date · datetime -> timestamptz · text -> text · enum -> native Postgres enum.
-- Nullability (the ERD only states one explicit case, reports.territory_key):
--   * primary keys and foreign keys drawn as "exactly one" (||) are NOT NULL
--   * reports.territory_key is nullable (null = All Territories)
--   * Source Finance Data attributes are nullable, since the raw Excel files contain blanks
--   * Application-Owned attributes are NOT NULL
-- Row Level Security is enabled on every table with no policies: the publishable (anon) key
-- can read/write nothing until policies are added; the service-role key bypasses RLS.

begin;

-- ===== Enums =====

create type coa_report          as enum ('profit_and_loss', 'balance_sheet', 'adjusting');
create type scenario_type       as enum ('base_case', 'custom');
create type report_type         as enum ('monthly_management_pack', 'board_pack', 'territory_review', 'variance_memo');
create type report_currency     as enum ('usd', 'local');
create type report_section_name as enum ('kpi_summary', 'profit_and_loss', 'territory_summary', 'ranked_variances', 'forecast_outlook');
create type validation_status   as enum ('pass', 'fail');

-- ===== Source Finance Data =====

create table territory (
  territory_key integer primary key,
  country       text,
  region        text
);

create table chart_of_accounts (
  account_key       integer primary key,
  report            coa_report,
  class             text,
  class_sorting     integer,
  sub_class         text,
  sub_class_sorting integer,
  sub_class2        text,
  sub_class2_sorting integer,
  account           text,
  account_sorting   integer,
  sub_account       text
);

create table calendar (
  date    date primary key,
  year    integer,
  quarter text,
  month   text,
  day     text
);

create table fiscal_years (
  year integer primary key
);

create table gl (
  id            integer generated by default as identity primary key,
  entry_no      numeric,
  date          date    not null references calendar (date),
  territory_key integer not null references territory (territory_key),
  account_key   integer not null references chart_of_accounts (account_key),
  details       text,
  amount        numeric
);

create table budget (
  id            integer generated by default as identity primary key,
  entry_no      text,
  date          date    not null references calendar (date),
  territory_key integer not null references territory (territory_key),
  account_key   integer not null references chart_of_accounts (account_key),
  details       text,
  type          text,
  amount        numeric
);

create table trial_balance (
  date          date    not null references calendar (date),
  territory_key integer not null references territory (territory_key),
  account_key   integer not null references chart_of_accounts (account_key),
  amount        numeric
);

create table currency_rate (
  date          date    not null references calendar (date),
  currency      text,
  exchange_rate numeric,
  territory_key integer not null references territory (territory_key)
);

create table cash_flow_mapping (
  type             text,
  subtype          text,
  account          text,
  sub_account      text,
  value_type       text,
  account_key      integer not null references chart_of_accounts (account_key),
  sort_on_type     integer,
  sort_on_sub_type integer
);

create table soce_mapping (
  type            text,
  account         text,
  balance_type    text,
  account_key     integer not null references chart_of_accounts (account_key),
  sort_by_type    integer,
  sort_by_account integer
);

-- ===== Application-Owned Data =====

create table scenarios (
  id                 text primary key default gen_random_uuid()::text,
  name               text          not null,
  territory_key      integer       not null references territory (territory_key),
  fiscal_year        integer       not null references fiscal_years (year),
  sales_growth       numeric       not null,
  price_change       numeric       not null,
  cost_of_sales_rate numeric       not null,
  opex_change        numeric       not null,
  headcount_change   integer       not null,
  scenario_type      scenario_type not null,
  last_saved_at      timestamptz   not null default now()
);

create table reports (
  id             text primary key default gen_random_uuid()::text,
  report_type    report_type     not null,
  territory_key  integer         references territory (territory_key),
  fiscal_year    integer         not null references fiscal_years (year),
  period         text            not null,
  currency       report_currency not null,
  frozen_figures text            not null,
  generated_at   timestamptz     not null default now()
);

create table report_sections (
  report_id    text                not null references reports (id),
  section_name report_section_name not null
);

create table datasets (
  name text primary key
);

create table dataset_sync_status (
  dataset_name      text              primary key references datasets (name),
  row_count         integer           not null,
  last_refreshed_at timestamptz       not null default now(),
  validation_status validation_status not null
);

create table dataset_issues (
  id           text primary key default gen_random_uuid()::text,
  dataset_name text not null references datasets (name),
  row_ref      text not null,
  message      text not null
);

-- ===== Reference data named in the ERD =====

insert into datasets (name) values
  ('gl'), ('budget'), ('trial_balance'), ('chart_of_accounts'), ('currency'),
  ('territory'), ('cash_flow_mapping'), ('soce'), ('calendar');

insert into fiscal_years (year) values (2023), (2024), (2025);

-- ===== Row Level Security: on, with no policies (deny by default) =====

alter table territory           enable row level security;
alter table chart_of_accounts   enable row level security;
alter table calendar            enable row level security;
alter table fiscal_years        enable row level security;
alter table gl                  enable row level security;
alter table budget              enable row level security;
alter table trial_balance       enable row level security;
alter table currency_rate       enable row level security;
alter table cash_flow_mapping   enable row level security;
alter table soce_mapping        enable row level security;
alter table scenarios           enable row level security;
alter table reports             enable row level security;
alter table report_sections     enable row level security;
alter table datasets            enable row level security;
alter table dataset_sync_status enable row level security;
alter table dataset_issues      enable row level security;

commit;
